#!/usr/bin/env python3
"""Write docs/CODEMAP.md from codegraph: a compact, always-current map of the code.

Codegraph keeps the code knowledge graph; this script snapshots its file structure into a
small doc that the docs index links to, so agents get the shape of the code without reading it.
Run by install-codegraph.sh and the docs-sync skill. No-op (exit 0) if codegraph isn't enabled.
"""
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "docs", "CODEMAP.md")
MAX_LINES = 120


def cg(*args):
    p = subprocess.run(["codegraph", *args], cwd=ROOT, capture_output=True, text=True, timeout=120,
                       env=dict(os.environ, CODEGRAPH_TELEMETRY="0"))
    return p.stdout.strip() if p.returncode == 0 else ""


def main():
    with open(os.path.join(ROOT, "factory.json"), encoding="utf-8") as fh:
        enabled = json.load(fh).get("integrations", {}).get("codegraph")
    if not enabled or not shutil.which("codegraph"):
        print("codemap: codegraph not enabled; skipped")
        return 0
    tree = cg("files", "--format", "tree", "--max-depth", "3").splitlines()
    status = "\n".join(l for l in cg("status", ".").splitlines() if not l.strip().startswith("Project:"))
    if len(tree) > MAX_LINES:
        tree = tree[:MAX_LINES] + ["… (truncated; run `codegraph files` for more)"]
    body = [
        "# Code map (generated)",
        "",
        "> Snapshot of the code structure from codegraph. Regenerated by `python3 scripts/codemap.py`. "
        "For questions about code, use `codegraph explore \"<question>\"` rather than reading files.",
        "",
        "## Index status",
        "",
        "```",
        status or "unavailable",
        "```",
        "",
        "## Files (depth 3)",
        "",
        "```",
        *tree,
        "```",
    ]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(body) + "\n")
    print("codemap: wrote docs/CODEMAP.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
